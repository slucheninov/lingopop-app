//! Marker-first NSPasteboard reads, enclosed in one changeCount generation.
use crate::{
    clipboard_observer::{ClipboardObservationSource, MAX_HISTORY_TEXT_BYTES},
    PlatformError,
};
use objc2::rc::autoreleasepool;
use objc2_app_kit::NSPasteboard;
use objc2_foundation::NSString;

pub(crate) struct MacObservationSource;
impl ClipboardObservationSource for MacObservationSource {
    fn generation(&self) -> u64 {
        autoreleasepool(|_| {
            u64::try_from(NSPasteboard::generalPasteboard().changeCount()).unwrap_or(0)
        })
    }
    fn read_generation(&self, expected: u64) -> Result<Option<String>, PlatformError> {
        super::clipboard_helper::read(expected, None)
    }
}

pub(super) fn read_pasteboard(
    pb: &NSPasteboard,
    expected: u64,
) -> Result<Option<String>, PlatformError> {
    if pb.changeCount() as u64 != expected {
        return Ok(None);
    }
    let items = pb.pasteboardItems().ok_or(PlatformError::ClipboardBusy)?;
    if items.len() > 256 {
        return Ok(None);
    }
    // Inspect all items, including items without text. Marker payload is irrelevant: presence is
    // enough, so an unreadable marker cannot accidentally make protected text eligible.
    for item in items.iter() {
        let types = item.types();
        if types.len() > 256 {
            return Ok(None);
        }
        for kind in types.iter() {
            if kind.length() > 1024 {
                return Ok(None);
            }
            if crate::clipboard_observer::macos_exclusion_marker(&kind.to_string()) {
                return Ok(None);
            }
        }
    }
    let mut text = None;
    for item in items.iter() {
        let kind = NSString::from_str(crate::pasteboard::TEXT_TYPE);
        if !item.types().iter().any(|t| t.isEqualToString(&kind)) {
            continue;
        }
        let data = item
            .dataForType(&kind)
            .ok_or(PlatformError::ClipboardBusy)?;
        if data.len() > MAX_HISTORY_TEXT_BYTES {
            return Ok(None);
        }
        // UTF-8 plain text only: invalid data fails closed, never lossy replacement.
        let bytes = data.to_vec();
        text = Some(
            String::from_utf8(bytes)
                .map_err(|_| PlatformError::Unsupported("clipboard text encoding"))?,
        );
        break;
    }
    if pb.changeCount() as u64 != expected {
        return Ok(None);
    }
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;
    use objc2::{rc::Retained, runtime::ProtocolObject};
    use objc2_app_kit::{NSPasteboardItem, NSPasteboardWriting};
    use objc2_foundation::{NSArray, NSData};
    // A private pasteboard never reads or modifies the user's clipboard.
    fn write(pb: &NSPasteboard, marker: Option<&str>, text: &[u8]) {
        pb.clearContents();
        let item = NSPasteboardItem::new();
        assert!(item.setData_forType(
            &NSData::with_bytes(text),
            &NSString::from_str(crate::pasteboard::TEXT_TYPE)
        ));
        let mut items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
            vec![ProtocolObject::from_retained(item)];
        if let Some(marker) = marker {
            // Marker on a separate, non-text item must still protect the entire pasteboard.
            let item = NSPasteboardItem::new();
            assert!(item.setData_forType(&NSData::with_bytes(&[]), &NSString::from_str(marker)));
            items.push(ProtocolObject::from_retained(item));
        }
        assert!(pb.writeObjects(&NSArray::from_retained_slice(&items)));
    }
    #[test]
    #[ignore = "needs interactive desktop; private named pasteboard only"]
    fn private_native_pasteboard_excludes_markers_and_preserves_contents() {
        autoreleasepool(|_| {
            let pb = NSPasteboard::pasteboardWithUniqueName();
            for marker in [
                "org.nspasteboard.TransientType",
                "org.nspasteboard.ConcealedType",
                "org.nspasteboard.AutoGeneratedType",
                "com.agilebits.onepassword",
            ] {
                write(&pb, Some(marker), b"private fixture");
                let generation = pb.changeCount() as u64;
                assert!(read_pasteboard(&pb, generation).unwrap().is_none());
                assert_eq!(generation, pb.changeCount() as u64);
            }
            write(&pb, None, b"ordinary copy");
            let generation = pb.changeCount() as u64;
            assert!(read_pasteboard(&pb, generation).unwrap().is_some());
            assert_eq!(generation, pb.changeCount() as u64);
            assert!(read_pasteboard(&pb, generation.wrapping_sub(1))
                .unwrap()
                .is_none());
            pb.clearContents();
        });
    }
    #[test]
    #[ignore = "needs interactive desktop; private named pasteboard only"]
    fn private_native_pasteboard_rejects_oversized_and_invalid_text() {
        autoreleasepool(|_| {
            let pb = NSPasteboard::pasteboardWithUniqueName();
            write(&pb, None, &vec![b'x'; MAX_HISTORY_TEXT_BYTES + 1]);
            assert!(read_pasteboard(&pb, pb.changeCount() as u64)
                .unwrap()
                .is_none());
            write(&pb, None, &[255]);
            assert!(read_pasteboard(&pb, pb.changeCount() as u64).is_err());
            pb.clearContents();
        });
    }
}
