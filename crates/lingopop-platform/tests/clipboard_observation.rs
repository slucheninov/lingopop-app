use lingopop_platform::clipboard_observer::{
    ClipboardObservationSource, ObservationCursor, MAX_HISTORY_TEXT_BYTES,
};
use lingopop_platform::PlatformError;
use std::sync::atomic::{AtomicU64, AtomicUsize, Ordering};
struct Source {
    generation: AtomicU64,
    reads: AtomicUsize,
    fail: bool,
    race: bool,
}
impl ClipboardObservationSource for Source {
    fn generation(&self) -> u64 {
        self.generation.load(Ordering::SeqCst)
    }
    fn read_generation(&self, _: u64) -> Result<Option<String>, PlatformError> {
        self.reads.fetch_add(1, Ordering::SeqCst);
        if self.fail {
            return Err(PlatformError::ClipboardBusy);
        }
        if self.race {
            self.generation.fetch_add(1, Ordering::SeqCst);
        }
        Ok(Some("foreign selection copy".into()))
    }
}
fn source() -> Source {
    Source {
        generation: AtomicU64::new(1),
        reads: AtomicUsize::new(0),
        fail: false,
        race: false,
    }
}
#[test]
fn startup_and_duplicate_notifications_do_not_read() {
    let s = source();
    let mut c = ObservationCursor::new(&s);
    assert!(c.observe(&s).unwrap().is_none());
    s.generation.store(2, Ordering::SeqCst);
    assert!(c.observe(&s).unwrap().is_some());
    assert!(c.observe(&s).unwrap().is_none());
    assert_eq!(s.reads.load(Ordering::SeqCst), 1);
}
#[test]
fn failed_read_is_retried_and_foreign_copy_is_not_suppressed() {
    let mut s = source();
    let mut c = ObservationCursor::new(&s);
    s.generation.store(2, Ordering::SeqCst);
    s.fail = true;
    assert!(c.observe(&s).is_err());
    s.fail = false;
    assert_eq!(
        c.observe(&s).unwrap().unwrap().text,
        "foreign selection copy"
    );
}
#[test]
fn generation_race_never_publishes_text() {
    let mut s = source();
    let mut c = ObservationCursor::new(&s);
    s.generation.store(2, Ordering::SeqCst);
    s.race = true;
    assert!(c.observe(&s).unwrap().is_none());
}
#[test]
fn diagnostics_hide_text() {
    use lingopop_platform::clipboard_observer::ClipboardObservation;
    let item = ClipboardObservation {
        revision: 0,
        generation: 2,
        text: "secret sentinel".into(),
    };
    assert!(!format!("{item:?}").contains("sentinel"));
    assert_eq!(MAX_HISTORY_TEXT_BYTES, 64 * 1024);
}

#[test]
fn exclusion_markers_fail_closed() {
    use lingopop_platform::clipboard_observer::{macos_exclusion_marker, windows_history_allowed};
    for marker in [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ] {
        assert!(macos_exclusion_marker(marker));
    }
    assert!(!macos_exclusion_marker("public.utf8-plain-text"));
    let zero = 0u32.to_le_bytes();
    let one = 1u32.to_le_bytes();
    assert!(windows_history_allowed(false, None, None));
    assert!(windows_history_allowed(false, Some(&one), Some(&one)));
    assert!(!windows_history_allowed(true, None, None));
    for flag in [&zero[..], &[][..], &[1][..], &[1, 0, 0, 0, 0][..]] {
        assert!(!windows_history_allowed(false, Some(flag), None));
        assert!(!windows_history_allowed(false, None, Some(flag)));
    }
}

