//! Owner-run, private pasteboards only. This executable explicitly dispatches the same helper
//! mode as the packaged application; libtest binaries cannot implement executable entry modes.
#[cfg(target_os = "macos")]
fn main() {
    use lingopop_platform::clipboard_observer::{
        dispatch_macos_clipboard_helper, read_isolated_macos_pasteboard, MAX_HISTORY_TEXT_BYTES,
    };
    use objc2::{rc::autoreleasepool, runtime::ProtocolObject};
    use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardWriting};
    use objc2_foundation::{NSArray, NSData, NSString};
    if dispatch_macos_clipboard_helper() {
        return;
    }
    if !std::env::args().any(|a| a == "--ignored") {
        return;
    }
    autoreleasepool(|_| {
        let pb = NSPasteboard::pasteboardWithUniqueName();
        let name = pb.name().to_string();
        let write = |bytes: &[u8], marker: Option<&str>| {
            pb.clearContents();
            let text = NSPasteboardItem::new();
            assert!(text.setData_forType(
                &NSData::with_bytes(bytes),
                &NSString::from_str("public.utf8-plain-text")
            ));
            let mut items = vec![ProtocolObject::<dyn NSPasteboardWriting>::from_retained(
                text,
            )];
            if let Some(marker) = marker {
                let item = NSPasteboardItem::new();
                assert!(item.setData_forType(&NSData::with_bytes(&[]), &NSString::from_str(marker)));
                items.push(ProtocolObject::from_retained(item));
            }
            assert!(pb.writeObjects(&NSArray::from_retained_slice(&items)));
            pb.changeCount() as u64
        };
        for marker in [
            "org.nspasteboard.TransientType",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
        ] {
            let generation = write(b"protected fixture", Some(marker));
            assert!(read_isolated_macos_pasteboard(&name, generation)
                .unwrap()
                .is_none());
            assert_eq!(pb.changeCount() as u64, generation);
        }
        let generation = write("ordinary multilingual copy: ї".as_bytes(), None);
        assert_eq!(
            read_isolated_macos_pasteboard(&name, generation)
                .unwrap()
                .as_deref(),
            Some("ordinary multilingual copy: ї")
        );
        assert!(
            read_isolated_macos_pasteboard(&name, generation.wrapping_sub(1))
                .unwrap()
                .is_none()
        );
        let generation = write(&vec![b'x'; MAX_HISTORY_TEXT_BYTES], None);
        assert_eq!(
            read_isolated_macos_pasteboard(&name, generation)
                .unwrap()
                .unwrap()
                .len(),
            MAX_HISTORY_TEXT_BYTES
        );
        let generation = write(&vec![b'x'; MAX_HISTORY_TEXT_BYTES + 1], None);
        assert!(read_isolated_macos_pasteboard(&name, generation)
            .unwrap()
            .is_none());
        let generation = write(&[255], None);
        assert!(read_isolated_macos_pasteboard(&name, generation).is_err());
        assert_eq!(pb.changeCount() as u64, generation);
        pb.clearContents();
    });
}
#[cfg(not(target_os = "macos"))]
fn main() {}
